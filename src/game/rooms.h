inline Rect get_tile_src(TileSprite s) {
    auto d = get_tile_sprite_def(s);
    return { static_cast<f32>(d.col * TILESET_CELL), static_cast<f32>(d.row * TILESET_CELL),
             static_cast<f32>(d.cells_w * TILESET_CELL), static_cast<f32>(d.cells_h * TILESET_CELL) };
}

// =============================================================================
// Room Type
// =============================================================================
enum class RoomType : u8 {
    Normal,      // Standard combat room
    Elite,       // Harder enemies, better reward
    Boss,        // Chapter boss
    Treasure,    // Free item
    Shop,        // Buy items with offerings
    Altar,       // Pray for faith
    Rest,        // Heal
    Event,       // Story/NPC event (widow, etc.)
    Start,
    Exit
};

inline bool is_combat_room(RoomType t) {
    return t == RoomType::Normal || t == RoomType::Elite || t == RoomType::Boss;
}

