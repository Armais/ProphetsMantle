// =============================================================================
// Room Map (floor layout - which rooms connect to which)
// =============================================================================
struct FloorMap {
    static constexpr int MAX_ROOMS = 25;  // hasta 5x5; hoy el techo real es 4x4

    struct RoomNode {
        RoomType type = RoomType::Normal;
        int grid_x = 0;
        int grid_y = 0;
        int connections[4] = {-1, -1, -1, -1};  // N, S, E, W -> room index
        int event_id = -1;   // solo en RoomType::Event: que escena del pozo cuenta esta sala
        // Enlace exterior <-> interior. En la sala de FUERA, `interior_room` es el indice de
        // su interior; en el INTERIOR, `interior_of` es el de su sala de fuera.
        int interior_room = -1;
        int interior_of   = -1;
    };

    RoomNode rooms[MAX_ROOMS];
    int room_count = 0;
    int current_room = 0;
    int boss_room = 0;
    int grid_w = 3;
    int grid_h = 3;

    // Dos ranuras (zona continua): 0 = la ZONA del capitulo (mientras el profeta esta en
    // un interior o en un escenario de escena), 1 = el INTERIOR (mientras esta fuera). Un
    // Room son ~15 KB: una ranura por nodo serian 375 KB para guardar flags. El estado de
    // cada celda vive en `Room::cells` de la zona.
    Room room_cache[2];
    bool room_generated[MAX_ROOMS] = {};   // nodo generado (las celdas, todas a la vez al construir la zona)
    bool zone_built = false;

    void generate(int chapter);
    int room_at(int gx, int gy) const;  // Find room index by grid coords, -1 if none
};
