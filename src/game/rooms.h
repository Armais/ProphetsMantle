// =============================================================================
// Tile Types (gameplay semantics; visuals come from TileSprite + biome)
// =============================================================================
enum class TileType : u8 {
    Floor = 0,
    Wall,        // Solid - cliff / stone wall (grid exterior + border segments)
    Pit,         // Hole - impassable
    Water,       // Slow movement (walkable)
    DoorNorth,
    DoorSouth,
    DoorEast,
    DoorWest,
    AltarBaal,   // Destructible - gives faith
    AltarGod,    // Pray - gives faith
    Chest,
    Tree,        // Solid - green obstacle
    Bush,        // Decorative - walkable
    Rock,        // Solid - gray obstacle
    TallGrass,   // Decorative - walkable, semi-transparent
    River,       // Solid - impassable water (canyon edge)
    Path,        // Walkable - worn dirt trail towards the exits
    Ford,        // Walkable - stepping stones across the river
    Bridge,      // Walkable - wooden planks across the river
    Exit,        // Walkable - chapter exit arch (appears when the boss falls)
    Torch,       // Decorative - walkable light source
    Event,       // Walkable - encuentro biblico: al pisarlo se abre el dialogo (game/events.h)
    Jar,         // Solid - tinaja: se rompe de un tiro y a veces esconde algo
    Crack,       // Solid - grieta en la roca: solo la abre el Fuego del Cielo
    Doorway,     // Walkable - puerta: al pisarla se entra a un interior (o se sale de el)
    COUNT
};

// =============================================================================
// Tileset (assets/sprites/tiles.png, generated by tools/blender/mantle_sprites/tiles.py)
// Cells are one tile (16 game units) = TILE_SIZE * ASSET_SCALE texels (64 px at x4),
// 8 columns. Keep in sync with tiles.LAYOUT / tiles.CELL.
// =============================================================================
// 2026-10-03: el tileset va al DOBLE (128 px por celda = 8 texeles por unidad) y se muestrea
// en LINEAL. Cada bloque lleva 2 px de margen con su borde extruido (tiles.py, GUTTER): sin
// el, el filtro lineal leeria la celda vecina del atlas en el borde de las celdas opacas. A
// 64 px y con `nearest` los props (arboles, rocas, hierba) se veian pixelados en cuanto la
// ventana pasaba de 1280x720.
constexpr int TILESET_TEXELS_PER_UNIT = Config::ASSET_SCALE * 2;                 // 8
constexpr int TILESET_CELL   = Config::TILE_SIZE * TILESET_TEXELS_PER_UNIT;      // 128
constexpr int TILESET_GUTTER = 2;
constexpr int TILESET_PITCH  = TILESET_CELL + 2 * TILESET_GUTTER;                // 132

enum class TileSprite : u8 {
    FloorA, FloorB, FloorC, FloorD, PathA, PathB, WaterA, WaterB,
    Cliff, Rock, Bush, Grass, Ford, Bridge, Chest, Pit,
    Tree, AltarGod, AltarBaal, Torch, Exit, TreeDead, Palm, CliffTall,
    Heart, Orb, Fireball, Lightbolt, Arrow, Darkbolt, Skull, Star,
    GrassA, GrassB, GrassC, GrassD, StoneA, StoneB, StoneC, StoneD,            // row 5: floor families
    DetTuftA, DetTuftB, DetPebbles, DetFlowers, DetCrack, DetTwigs, DetBones, DetMoss,   // row 6: ground decals
    ShoreEdge, ShoreOut, ShoreIn,      // row 7: water banks, authored for N (rotated 90/180/270 when drawn)
    CliffRock, CliffRockTall,          // rows 7-8: cara de ROCA (bordes Cliff/Natural); Cliff* sigue siendo silleria
    Jar, Crack,                        // row 7: secretos de bioma (GDD2.0 fase 4)
    Door,                              // rows 7-8: puerta a un interior (GDD2.0 fase 3)
    COUNT
};

