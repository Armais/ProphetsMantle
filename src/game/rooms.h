// =============================================================================
// Room Map (floor layout - which rooms connect to which)
// =============================================================================
struct FloorMap {
    static constexpr int MAX_ROOMS = 16;  // Enough for 4x4 grid

    struct RoomNode {
        RoomType type = RoomType::Normal;
        int grid_x = 0;
        int grid_y = 0;
        int connections[4] = {-1, -1, -1, -1};  // N, S, E, W -> room index
    };

    RoomNode rooms[MAX_ROOMS];
    int room_count = 0;
    int current_room = 0;
    int boss_room = 0;
    int grid_w = 3;
    int grid_h = 3;

    // Room cache for persistence (re-entering a visited room restores from cache)
    Room room_cache[MAX_ROOMS];
    bool room_generated[MAX_ROOMS] = {};

    void generate(int chapter);
    int room_at(int gx, int gy) const;  // Find room index by grid coords, -1 if none
};
